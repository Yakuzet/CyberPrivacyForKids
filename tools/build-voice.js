/* Pre-records every spoken line with free Microsoft neural voices (edge-tts).
   Usage:   python -m pip install edge-tts
            node tools/build-voice.js
   Re-run after editing any text — only new/changed lines are recorded. */
const fs = require("fs");
const path = require("path");
const vm = require("vm");
const { spawn } = require("child_process");

const VOICES = {
  kid:    { voice: "en-US-EmmaNeural",        rate: "-5%",  pitch: "+0Hz" },
  horror: { voice: "en-US-ChristopherNeural", rate: "-12%", pitch: "-12Hz" }
};
const CONCURRENCY = 4;

const root = path.join(__dirname, "..");
const outDir = path.join(root, "audio");
const tmpDir = path.join(outDir, ".tmp");
fs.mkdirSync(tmpDir, { recursive: true });

// Load the site's own content + speech builders so the lines match exactly
const src = ["js/content.js", "js/speech.js"].map((f) => fs.readFileSync(path.join(root, f), "utf8")).join("\n");
const ctx = vm.createContext({ TextEncoder });
vm.runInContext(src + "\nthis.__lines = SPEECH.all().map(l => ({...l, key: SPEECH.key(l.mode, l.text)}));", ctx);
const lines = ctx.__lines;

const todo = lines.filter((l) => !fs.existsSync(path.join(outDir, l.key + ".mp3")));
console.log(`${lines.length} lines · ${lines.length - todo.length} already recorded · ${todo.length} to record`);

function record(l) {
  return new Promise((resolve) => {
    const v = VOICES[l.mode];
    const txt = path.join(tmpDir, l.key + ".txt");
    fs.writeFileSync(txt, l.text, "utf8");
    const out = path.join(outDir, l.key + ".mp3");
    const args = ["-m", "edge_tts", "--voice", v.voice, `--rate=${v.rate}`, `--pitch=${v.pitch}`, "-f", txt, "--write-media", out];
    const tryOnce = (n) => {
      const p = spawn("python", args, { stdio: ["ignore", "ignore", "pipe"] });
      let err = "";
      p.stderr.on("data", (d) => (err += d));
      p.on("close", (code) => {
        if (code === 0 && fs.existsSync(out) && fs.statSync(out).size > 0) return resolve(true);
        if (n < 3) return setTimeout(() => tryOnce(n + 1), 1500 * n);
        try { fs.unlinkSync(out); } catch (e) {}
        console.error(`✗ failed: "${l.text.slice(0, 60)}"\n${err.trim().split("\n").pop()}`);
        resolve(false);
      });
    };
    tryOnce(1);
  });
}

(async () => {
  let done = 0, failed = 0, i = 0;
  const worker = async () => {
    while (i < todo.length) {
      const l = todo[i++];
      if (!(await record(l))) failed++;
      done++;
      process.stdout.write(`\r  recorded ${done}/${todo.length}`);
    }
  };
  await Promise.all(Array.from({ length: CONCURRENCY }, worker));
  if (todo.length) process.stdout.write("\n");
  fs.rmSync(tmpDir, { recursive: true, force: true });

  // Remove clips for text that no longer exists, then write the manifest
  const keep = new Set(lines.map((l) => l.key));
  for (const f of fs.readdirSync(outDir)) {
    if (f.endsWith(".mp3") && !keep.has(f.slice(0, -4))) fs.unlinkSync(path.join(outDir, f));
  }
  const have = lines.filter((l) => fs.existsSync(path.join(outDir, l.key + ".mp3"))).map((l) => l.key);
  fs.writeFileSync(path.join(outDir, "manifest.js"),
    `/* generated by tools/build-voice.js — do not edit */\nwindow.VOICE_CLIPS = ${JSON.stringify(have)};\n`);
  console.log(`Done. ${have.length}/${lines.length} clips available${failed ? `, ${failed} failed (those fall back to the browser voice)` : ""}.`);
})();
